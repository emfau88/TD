test('real schema 32 in-flight replay preserves every field and old reward until the next attempt',()=>{
  const original=structuredClone(legacy.before),b=IdleBattle.restore(original)!;assert.ok(b);
  const promote=(s:any)=>({...s,settlement:{...s.settlement,emberResearched:false,emberResearchSeen:false},social:{...s.social,encounters:expectedEmptyEncounters()},schemaVersion:BATTLE_SCHEMA_VERSION,rulesVersion:BATTLE_RULES_VERSION});
  assert.deepEqual(b.snapshot(),promote(legacy.before));assert.deepEqual(original,legacy.before);
  const before=units(b);
  for(let i=0;i<160;i++)b.update(.025);
  assert.deepEqual(b.snapshot(),promote(legacy.after));assert.equal(units(b)-before,29700);
  assert.deepEqual(IdleBattle.restore(b.snapshot())!.snapshot(),b.snapshot());
  const attempt=b.attemptId;until(b,()=>b.attemptId>attempt);
  assert.equal(b.waveRecipeVersion,BATTLE_RULES_VERSION);
  assert.equal(isFarmCertificateValid(legacy.proof,b),false);
  const proof=certifyFarm(b,legacy.proof)!;assert.ok(proof);assert.equal(proof.rulesVersion,BATTLE_RULES_VERSION);
  // New compositions may change the best farm, but not the repeat-gold policy.
  assert.equal(proof.wave,20);assert.ok(isFarmCertificateValid(proof,b));
  const first=Array.from({length:waveCount(proof.wave)},(_,i)=>waveEnemy(proof.wave,i)).reduce(
    (sum,e)=>sum+battleRewardUnits(e.gold,proof.wave,BATTLE_RULES_VERSION,true,false),
    battleRewardUnits(clearReward(proof.wave,BATTLE_RULES_VERSION),proof.wave,BATTLE_RULES_VERSION,true,false));
  assert.equal(farmRewardUnits(proof)*10n,BigInt(first)*2n); // certificate spans two full cycles
});

test('native session preserves old 60/65% active baselines and pending claims exactly once, then starts new policy',async()=>{
  for(const policy of [LEGACY_OFFLINE,LEGACY_WAREHOUSE_OFFLINE])for(const pending of [false,true]){
    const factory=new IDBFactory(),name=`economy-${policy.efficiencyPermille}-${pending}`;
    const start=1000,now=start+86400000;
    const old=structuredClone(legacy.before);
    if(policy===LEGACY_OFFLINE){old.settlement.warehouseBuilt=false;old.settlement.warehouseBuiltAt=null;}
    let offline=checkpointActive(createOfflineState(start),start,legacy.proof,false,policy);
    if(pending)offline=reserveOffline(offline,start+3600000);
    const initialStore=await openBattleStore(factory,name,()=>now);initialStore.close();
    await new Promise<void>((resolve,reject)=>{
      const q=factory.open(name,1);q.onerror=()=>reject(q.error);q.onsuccess=()=>{
        const db=q.result,tx=db.transaction('saves','readwrite');
        tx.objectStore('saves').put({schemaVersion:2,revision:1,writtenAt:start,paused:false,battle:old,offline},'default');
        tx.oncomplete=()=>{db.close();resolve();};tx.onerror=()=>reject(tx.error);
      };
    });
    let session=await BattleSession.open(await openBattleStore(factory,name,()=>now),{now:()=>now,locks:null});
    const expected=Number(farmRewardUnits(legacy.proof)*BigInt(policy.efficiencyPermille)*BigInt(policy.limitMs)/(BigInt(legacy.proof.durationMs)*1000n));
    assert.equal(session.pendingReward!.amountUnits,expected);assert.equal(session.pendingReward!.creditedMs,policy.limitMs);
    const oldUnits=units(session.battle);await session.close();
    session=await BattleSession.open(await openBattleStore(factory,name,()=>now),{now:()=>now,locks:null});
    assert.equal(session.pendingReward!.amountUnits,expected);
    assert.equal(await session.claimOffline(),true);assert.equal(await session.claimOffline(),false);
    assert.equal(units(session.battle),oldUnits+expected);
    assert.equal(session.battle.elapsed,old.elapsed);assert.equal(session.battle.wave,old.wave);
    assert.equal(await session.resumeActive(),true);
    assert.equal(session.offline.baseline.efficiencyPermille,policy===LEGACY_OFFLINE?240:260);
    assert.equal(session.offline.baseline.certificate!.rulesVersion,BATTLE_RULES_VERSION);
    await session.close();
  }
});

test('new policy fractions survive repeated claims and reloads without a second multiplier or reset',()=>{
  const b=IdleBattle.restore(legacy.before)!,proof=certifyFarm(b)!;
  const initial=beginAbsence(createOfflineState(0),0,proof,false,WAREHOUSE_OFFLINE);
  let state=initial,total=0;
  for(const time of [1,7,30000,1800000,7200000,28800000,86400000]){
    state=reserveOffline(restoreOffline(JSON.parse(JSON.stringify(state)))!,time);
    const id=state.pendingReward!.id,claimed=claimOffline(state,id);total+=claimed.amountUnits;state=claimed.state;
    assert.equal(claimOffline(state,id).amountUnits,0);
  }
  assert.equal(total,reserveOffline(initial,86400000).pendingReward!.amountUnits);
  assert.equal(state.window!.usedMs,28800000);
});
