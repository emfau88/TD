"""Pack original Foozle PNG frames unchanged; no resampling or generated art.
Run from any directory. Original ZIPs/Readmes remain the source of truth.
"""
from pathlib import Path
from PIL import Image
import zipfile, io, json, struct, hashlib

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/lucifer'
SPECS = [('ForestGoblin','goblin'),('BoneGuard','skeleton'),('ForestCultist','cultist')]

def durations(data):
    count = struct.unpack_from('<H', data, 6)[0]
    result, pos = [], 128
    for _ in range(count):
        result.append(struct.unpack_from('<H', data, pos+8)[0])
        pos += struct.unpack_from('<I', data, pos)[0]
    return result

metadata, provenance = {}, {}
for kind, archive in SPECS:
    path = OUT / 'sources' / (archive+'.zip')
    if not path.exists(): continue
    frames, clips, sources = [], {}, {}
    with zipfile.ZipFile(path) as z:
        readme = next(n for n in z.namelist() if n.lower().endswith('readme.txt'))
        license = z.read(readme)
        assert b'CC0' in license and b'commercial' in license
        (OUT / (archive+'-LICENSE.txt')).write_bytes(license)
        for direction, folder in [('down','Down'),('up','Up'),('side','Right'),('left','Left')]:
            for action in (['move','heal'] if kind=='ForestCultist' else ['move']):
                suffixes = ('Run.png','Walk.png') if action=='move' else ('Attack01.png',)
                name = next(n for n in z.namelist() if '/'+folder+'/Png/' in n and n.endswith(suffixes))
                im = Image.open(io.BytesIO(z.read(name))).convert('RGBA')
                assert im.height==48 and im.width%48==0
                ase = name.replace('/Png/','/Ase/').replace('.png','.aseprite')
                times = durations(z.read(ase))
                selected = list(range(im.width//48)) if action=='move' else [0,1,2,3]
                mapping = []
                for index in selected:
                    tile = Image.new('RGBA',(64,64))
                    tile.alpha_composite(im.crop((index*48,0,(index+1)*48,48)),(8,0))
                    assert tile.getbbox() and tile.getbbox()[2]<=62 and tile.getbbox()[3]<=62
                    mapping.append(len(frames)); frames.append(tile)
                clips.setdefault(action,{})[direction]={'frames':mapping,'durations':[times[i] for i in selected] if action=='move' else [100]*4}
                sources[action+'/'+direction]={'png':name,'aseprite':ase,'sourceFrames':selected,'sourceFrameSize':[48,48],'offset':[8,0]}
    sheet=Image.new('RGBA',(512,64*((len(frames)+7)//8)))
    for index,tile in enumerate(frames): sheet.alpha_composite(tile,((index%8)*64,(index//8)*64))
    sheet.save(OUT/(kind+'.png'),optimize=True)
    metadata[kind]={'width':64,'height':64,'scale':.83,'facesLeft':False,**clips}
    provenance[kind]={'archive':archive+'.zip','sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'runtimeBytes':(OUT/(kind+'.png')).stat().st_size,'frames':len(frames),'sources':sources}
(OUT/'animations.json').write_text(json.dumps(metadata,indent=2)+'\n',encoding='utf-8')
(OUT/'provenance.json').write_text(json.dumps(provenance,indent=2)+'\n',encoding='utf-8')
(ROOT/'src/lucifer-frames.ts').write_text('// Generated by scripts/pack-lucifer.py from original CC0 PNG/Aseprite frames.\nexport const LUCIFER_FRAMES = '+json.dumps(metadata,indent=2)+' as const;\n',encoding='utf-8')
print(json.dumps({kind:{'bytes':data['runtimeBytes'],'frames':data['frames']} for kind,data in provenance.items()}))
