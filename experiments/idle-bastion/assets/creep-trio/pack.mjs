import {createRequire} from 'node:module';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const sharp=createRequire(import.meta.url)('C:/Users/madde/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
const path=p=>fileURLToPath(new URL(p,import.meta.url));
const blank=(w,h)=>sharp({create:{width:w,height:h,channels:4,background:'#00000000'}});
const definitions={};
for(const [source,id] of [['flame-wisp-orange','FlameWisp'],['floating-eye-purple','FloatingEye']]){
 const meta=JSON.parse(await readFile(path(`sources/${source}.json`),'utf8'));
 const merged=await sharp(path(`sources/${source}_outline_lit.png`)).composite([{input:path(`sources/${source}_outline_shine.png`)}]).png().toBuffer();
 const move={},tiles=[];
 for(const [row,[side,direction]]of [['South','down'],['East','side'],['North','up'],['West','left']].entries()){
  const frames=meta.frames.filter(f=>f.pixor.action==='Idle'&&f.pixor.side===side).sort((a,b)=>a.pixor.index-b.pixor.index);
  move[direction]={frames:frames.map((_,i)=>row*8+i),durations:frames.map(f=>f.duration)};
  for(const [i,f]of frames.entries()){
   const input=await sharp(merged).extract({left:f.frame.x,top:f.frame.y,width:f.frame.w,height:f.frame.h}).png().toBuffer();
   tiles.push({input,left:i*64+32-f.pixor.pivot.x,top:row*64+43-f.pixor.pivot.y});
  }
 }
 await blank(512,256).composite(tiles).png().toFile(path(id+'.png'));
 definitions[id]={key:'idle-enemy-'+id,width:64,height:64,scale:.83,facesLeft:false,move};
}
function bounds(data,info){let l=info.width,t=info.height,r=-1,b=-1;for(let y=0;y<info.height;y++)for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*4+3]>127){l=Math.min(l,x);r=Math.max(r,x);t=Math.min(t,y);b=Math.max(b,y);}return{left:l,top:t,width:r-l+1,height:b-t+1};}
const tiles=[],move={},durations=[150,100,100,180,100,130];
for(const [row,direction]of ['side','down','up'].entries()){
 const source=path(`sources/slime-${direction}.png`),m=await sharp(source).metadata(),cells=[];
 for(let i=0;i<6;i++){
  const {data,info}=await sharp(source).extract({left:i%3*m.width/3,top:Math.floor(i/3)*m.height/2,width:m.width/3,height:m.height/2}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  for(let j=3;j<data.length;j+=4)data[j]=data[j]>127?255:0;
  cells.push({data,info,b:bounds(data,info)});
 }
 // Stable scale within a direction retains the generated squash/stretch.
 const scale=direction==='side'?34/cells[0].b.width:27/cells[0].b.height;
 for(const [i,{data,info,b}]of cells.entries()){
  const w=Math.round(b.width*scale),h=Math.round(b.height*scale);
  const input=await sharp(data,{raw:info}).extract(b).resize(w,h,{kernel:'nearest'}).png().toBuffer();
  tiles.push({input,left:i*64+Math.round(32-w/2),top:row*64+43-h});
 }
 move[direction]={frames:Array.from({length:6},(_,i)=>row*6+i),durations};
}
await blank(384,192).composite(tiles).png({palette:true,colours:16,dither:0}).toFile(path('CobaltSlime.png'));
definitions.CobaltSlime={key:'idle-enemy-CobaltSlime',width:64,height:64,scale:.83,facesLeft:false,move};
await writeFile(path('../../src/creep-trio-frames.ts'),'// Generated by assets/creep-trio/pack.mjs; source art and provenance stay alongside it.\nexport const CREEP_TRIO_FRAMES = '+JSON.stringify(definitions)+' as const;\n');
