"""Measure approved Ilyra tavern/command lines against Mara; write gains, never re-encode."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import statistics
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--ffmpeg', default='ffmpeg')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
game = root / 'experiments/idle-bastion'
names = ['giggle1', 'good1', 'goodboy1', 'lookonlyatme1', 'senpai1', 'sweetheart1', 'wouldntyou1']
commands = ['senpai1', 'senpai2', 'senpai3', 'sweetheart1', 'sweetheart2', 'sweetheart3', 'youremine1']
mara_commands = ['P11', 'P09', 'P07', 'P06', 'P03', 'P01', 'P14']

def measure(path):
    run = subprocess.run([args.ffmpeg, '-hide_banner', '-i', str(path), '-af',
                          'loudnorm=I=-23:TP=-2:LRA=7:print_format=json', '-f', 'null', '-'],
                         capture_output=True, text=True, check=True)
    data = json.loads(re.search(r'\{\s*"input_i".*?\}', run.stderr, re.S).group())
    return {'file': path.name, 'bytes': path.stat().st_size,
            'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
            'integratedLufs': float(data['input_i']), 'truePeakDbtp': float(data['input_tp'])}

mara = [measure(path) for path in sorted((game / 'assets/mara-voice').glob('*.wav'))]
target = statistics.median(row['integratedLufs'] for row in mara)
measured = {name: measure(game / 'assets/ilyra-voice' / f'voice1-{name}.mp3') for name in dict.fromkeys(names + commands)}
mara_command_rows = [measure(game / 'assets/mara-command-voice' / f'{name}.wav') for name in mara_commands]
for row in [*measured.values(), *mara_command_rows]:
    row['gainDb'] = round(target - row['integratedLufs'], 6)
    row['gain'] = round(10 ** (row['gainDb'] / 20), 8)
    row['adjustedTruePeakDbtp'] = round(row['truePeakDbtp'] + row['gainDb'], 3)
    playback = 0.5 if row in mara_command_rows else 0.7
    assert math.isfinite(row['gain']) and row['adjustedTruePeakDbtp'] + 20 * math.log10(playback) < -3
ilyra = [measured[name] for name in names]
command_rows = [measured[name] for name in commands]
report = {'method': 'FFmpeg loudnorm input measurement (EBU R128); constant playback gain per clip',
          'targetLufs': target, 'reference': 'Median of the ten unchanged Mara source clips',
          'sharedPlaybackGain': 0.7, 'commandPlaybackGain': 0.5, 'subjectiveListeningApproval': False,
          'mara': mara, 'ilyra': ilyra, 'commands': command_rows, 'maraCommands': mara_command_rows}
(game / 'assets/ilyra-voice/levels.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8', newline='\n')
table = '\n'.join(f"  '{row['file']}': {row['gain']}," for row in ilyra)
command_table = '\n'.join(f"  '{row['file']}': {row['gain']}," for row in command_rows)
mara_table = '\n'.join(f"  '{row['file']}': {row['gain']}," for row in mara_command_rows)
(game / 'src/ilyra-voice-levels.ts').write_text(
    '// Generated by scripts/measure-tavern-voices.py. Source MP3s remain unchanged.\n'
    '// Match Mara\'s median source loudness; both pools share the 0.7 playback factor.\n'
    'export const ILYRA_VOICE_GAINS = {\n' + table + '\n} as const;\n'
    'export const ILYRA_COMMAND_VOICE_GAINS = {\n' + command_table + '\n} as const;\n'
    'export const MARA_COMMAND_VOICE_GAINS = {\n' + mara_table + '\n} as const;\n', encoding='utf-8', newline='\n')
print(json.dumps({'targetLufs': target, 'commandPlaybackGain': 0.5, 'maraCommands': mara_command_rows}))
